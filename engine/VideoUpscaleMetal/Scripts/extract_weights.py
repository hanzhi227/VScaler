#!/usr/bin/env python3
"""
Extract Anime4K v3.2 Upscale-CNN-x2-(M) convolution weights from the upstream
GLSL shaders and emit them as exact Swift `Float` array literals.

Why this script exists: the weights must NOT be hand-transcribed. This parses
the GLSL `mat4(...)` / `vec4(...)` constructor literals directly, preserving
order and semantics.

GLSL semantics reproduced by the Metal port:
  * `mat4(a,b,c,d, e,f,g,h, i,j,k,l, m,n,o,p)` is COLUMN-major: column j = m[4j..4j+3].
  * `M * v` => out[c] = sum_j m[4*j + c] * v[j].
  * Pass structure (Upscale_CNN_x2_M.glsl v3.2):
      0: Conv-4x3x3x3   : 9  mat4 (9 neighbour offsets), +vec4 bias
      1..6: Conv-4x3x3x8: 18 mat4 (9 offsets x {pos,neg}), +vec4 bias
      7: Conv-4x1x1x56  : 14 mat4 (7 feature maps x {pos,neg}), +vec4 bias
      8: Depth-to-Space : no weights (fixed pixel-shuffle + bilinear add)
  * Neighbour offset order for the 3x3 convs, exactly as written in the GLSL:
      (-1,-1) (-1,0) (-1,1) (0,-1) (0,0) (0,1) (1,-1) (1,0) (1,1)
    for the first (positive) half, then the same 9 offsets for the negative half.

Usage:
  python3 extract_weights.py <shader.glsl> <SymbolPrefix> <out.swift> [--append]

The denoise variant has a byte-identical structure (only the numeric values
differ), so the same parser is used for both.
"""

import json
import re
import sys
from pathlib import Path

MAT_RE = re.compile(r"mat4\(([^)]*)\)")
BIAS_RE = re.compile(r"result\s*\+=\s*vec4\(([^)]*)\)")
FLOAT_RE = re.compile(r"[-+]?(?:\d+\.?\d*|\.\d+)(?:[eE][-+]?\d+)?")

EXPECTED_MATS = [9, 18, 18, 18, 18, 18, 18, 14, 0]
EXPECTED_BIAS = [4, 4, 4, 4, 4, 4, 4, 4, 0]


def parse_floats(text: str):
    return [float(x) for x in FLOAT_RE.findall(text)]


def parse_shader(path: Path):
    text = path.read_text()
    # Split after the *first* "vec4 hook()" header line. Because each pass's
    # metadata block (//!DESC, //!BIND, #define ...) precedes its "vec4 hook()",
    # the bodies land cleanly in chunks[1:].
    chunks = text.split("vec4 hook()")
    if len(chunks) != 10:
        raise SystemExit(f"expected 9 hook bodies, found {len(chunks) - 1}")
    passes = []
    for i in range(9):
        body = chunks[i + 1]
        mats = [parse_floats(m) for m in MAT_RE.findall(body)]
        bias_matches = BIAS_RE.findall(body)
        bias = parse_floats(bias_matches[-1]) if bias_matches else []
        for m in mats:
            if len(m) != 16:
                raise SystemExit(f"pass {i}: mat4 with {len(m)} floats")
        if len(mats) != EXPECTED_MATS[i]:
            raise SystemExit(
                f"pass {i}: expected {EXPECTED_MATS[i]} mat4, found {len(mats)}"
            )
        if len(bias) != EXPECTED_BIAS[i]:
            raise SystemExit(
                f"pass {i}: expected {EXPECTED_BIAS[i]} bias floats, found {len(bias)}"
            )
        passes.append({"mats": mats, "bias": bias})
    return passes


def flat(p) -> list:
    out = []
    for m in p["mats"]:
        out.extend(m)
    out.extend(p["bias"])
    return out


def swift_literal(values, indent="        ", per_line=8):
    lines = []
    for i in range(0, len(values), per_line):
        chunk = values[i : i + per_line]
        lines.append(
            indent + ", ".join(repr(float(v)) for v in chunk) + ","
        )
    return "\n".join(lines)


def emit_swift(prefix: str, passes, source_name: str, header_note: str) -> str:
    conv1 = flat(passes[0])
    mid = [flat(passes[i]) for i in range(1, 7)]
    last = flat(passes[7])
    lines = []
    lines.append("// Generated by Scripts/extract_weights.py -- DO NOT EDIT BY HAND.")
    lines.append(f"// Source: {source_name} (Anime4K v3.2, MIT License, bloc97).")
    lines.append(f"// {header_note}")
    lines.append("//")
    lines.append("// Weight layouts consumed by the Metal kernels:")
    lines.append("//   conv1  : 9 * mat4 (offsets (-1,-1)..(1,1))          + bias4 = 148 floats")
    lines.append("//   convMid: 9 * mat4 (positive) then 9 * mat4 (negative) + bias4 = 292 floats")
    lines.append("//   convLast: 14 * mat4 (7 maps x {pos,neg})              + bias4 = 228 floats")
    lines.append("// GLSL mat4 is column-major; kernels use out[c] = sum_j m[4*j+c]*v[j].")
    lines.append("")
    lines.append(f"enum {prefix}Weights {{")
    lines.append(f"    static let conv1: [Float] = [")
    lines.append(swift_literal(conv1))
    lines.append("    ]")
    lines.append("")
    lines.append(f"    static let convMid: [[Float]] = [")
    for i, arr in enumerate(mid):
        lines.append(f"        [ // pass {i + 2} of 9")
        lines.append(swift_literal(arr, indent="            "))
        lines.append("        ],")
    lines.append("    ]")
    lines.append("")
    lines.append(f"    static let convLast: [Float] = [")
    lines.append(swift_literal(last))
    lines.append("    ]")
    lines.append("}")
    lines.append("")
    return "\n".join(lines)


def main():
    if len(sys.argv) < 4:
        raise SystemExit(__doc__)
    shader = Path(sys.argv[1])
    prefix = sys.argv[2]
    out = Path(sys.argv[3])
    append = "--append" in sys.argv[4:]
    note = " ".join(a for a in sys.argv[4:] if not a.startswith("--"))

    passes = parse_shader(shader)
    swift = emit_swift(prefix, passes, shader.name, note)

    if append and out.exists():
        out.write_text(out.read_text() + "\n" + swift)
    else:
        out.write_text(swift)

    summary = {
        "shader": str(shader),
        "prefix": prefix,
        "pass_floats": [len(flat(p)) for p in passes],
        "total_floats": sum(len(flat(p)) for p in passes),
        "bias": [p["bias"] for p in passes],
        "out": str(out),
    }
    print(json.dumps(summary, indent=2))


if __name__ == "__main__":
    main()
