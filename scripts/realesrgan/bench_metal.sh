#!/usr/bin/env bash
# Regenerate results/general/realesrgan_metal.txt — everything measured about
# running Real-ESRGAN *live*, as opposed to offline. Both checkpoints: the
# animevideov3 mode that shipped first, and general-x4v3 (`--mode
# realesrgan-general`), which is a mode too.
#
# The order matters: the primitive rates come first so the design decision they
# justify is legible next to the result, then the model, then the player.
#
#   scripts/realesrgan/bench_metal.sh
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
cd "$ROOT"

OUT="$ROOT/results/general/realesrgan_metal.txt"
PKG="$ROOT/engine/RealESRGANMetal"
LOG="$(mktemp)"
trap 'rm -f "$LOG"' EXIT

say() { printf '\n\033[1m== %s\033[0m\n' "$*"; }

{
echo "Real-ESRGAN animevideov3 as a LIVE mode — raw measurements"
echo "generated by scripts/realesrgan/bench_metal.sh on $(date '+%Y-%m-%d %H:%M')"
echo "host: $(sysctl -n machdep.cpu.brand_string 2>/dev/null || sw_vers -productName), $(sw_vers -productVersion)"
# Recorded because it changes the answer: these are GPU measurements, and the
# player also uses the GPU. A load average near zero is a clean run; anything
# else scales every absolute figure here, which is why the ratio between the two
# checkpoints is the number to trust when the machine is busy.
echo "load average: $(sysctl -n vm.loadavg)"

say "1. GPU primitive rates (scripts/bench_alu_throughput.swift)"
echo "Why first: these decide whether a hand-written kernel can beat MPS, and"
echo "the answer is no. The network needs 160.7 GFLOP at 480x270, against an"
echo "fp16 ceiling of 8.4 TFLOP/s — so a perfect SIMT kernel reaches ~19 ms and"
echo "a realistic one is worse, while MPSGraph already runs at ~7.1 TFLOP/s"
echo "effective. simdgroup_matrix was measured and is SLOWER, not faster."
xcrun -sdk macosx swiftc -O scripts/bench_alu_throughput.swift -o /tmp/alubench -framework Metal 2>/dev/null
/tmp/alubench
xcrun -sdk macosx swiftc -O scripts/bench_matrix_throughput.swift -o /tmp/matbench -framework Metal 2>/dev/null
/tmp/matbench

say "2. The port: MPSGraph + 2 Metal kernels (engine/RealESRGANMetal)"
swift build -c release --package-path "$PKG" >"$LOG" 2>&1 || { cat "$LOG"; exit 1; }
echo "-- animevideov3 (the shipped mode)"
"$PKG/.build/release/resrbench" --bench --iters 10
echo
echo "-- general-x4v3 (32 body convs, twice the arithmetic; --mode realesrgan-general)"
echo "   Its cost is ~1.8-1.9x animevideov3 at every size, and it loses on picture"
echo "   to animevideov3 on both content types. It is still a mode, so it can be"
echo "   judged on real footage -- see scripts/realesrgan/README.md and"
echo "   scripts/realesrgan/pair_grid.sh."
"$PKG/.build/release/resrbench" --bench --variant general-x4v3 --iters 10

say "3. Is it the same model? (scripts/realesrgan/verify_metal.py)"
echo "vs fp32 CPU = what the model ideally produces (the gap is the price of"
echo "fp16, not a bug). vs fp16 MPS = a different runtime doing the same"
echo "arithmetic; that gap should be noise, and it is."
python3 scripts/realesrgan/verify_metal.py --size 480x270

say "4. In the player, 4x, end to end (playercheck)"
swift build -c release --package-path "$ROOT/engine/MacVideoUpscaler" >"$LOG" 2>&1 || { cat "$LOG"; exit 1; }
PC="$ROOT/engine/MacVideoUpscaler/.build/release/playercheck"

run_player() {  # run_player <label> <file> <scale> <seconds>
  local label="$1" file="$2" scale="$3" secs="$4"
  echo
  echo "--- $label"
  "$PC" --file "$file" --mode realesrgan --scale "$scale" --seconds "$secs" --no-audio 2>/dev/null \
    | tail -1 | python3 -c '
import json, sys
d = json.load(sys.stdin)
print("  source   %dx%d" % (d["sourceWidth"], d["sourceHeight"]))
print("  output   %dx%d" % (d["outputWidth"], d["outputHeight"]))
print("  mode     %s" % d["mode"])
if d["framesProcessed"]:
    print("  frames   %d in %.2fs   %.2f fps   %.4fx realtime   %.0f MB footprint"
          % (d["framesProcessed"], d["playbackSeconds"], d["processFps"],
             d["realtimeRatio"], d["memoryFootprintMB"]))
print("  state    %s" % d["state"])
if d["message"]:
    print("  message  %s" % d["message"])
'
}

run_player "640x480 anime, 4x -> 2560x1920" test-media/segments/naruto_t290.mkv 4 12
run_player "960x540 anime, 4x -> 3840x2160 (the largest that fits the encoder)" \
    test-media/general/naruto_540p_c30.mp4 4 10
run_player "480x270 anime, asked for 2x (the mode pins itself to 4x)" \
    test-media/general/naruto_270p_c28.mp4 2 6
run_player "1920x1080 anime, 4x would be 7680x4320 — must refuse, not clamp" \
    test-media/segments/naruto_1080p_aligned.mkv 4 3

say "5. On picture, through the same scored harness as every other mode"
echo "See results/general/{anime,liveaction}_270p_to_1080p_4x/metrics.json:"
echo "  live action — acutance 0.97x of the truth, the only mode within 3%"
echo "  anime       — PSNR 28.36 against the Anime4K CNN's 35.52"
} > "$OUT" 2>&1

echo "wrote $OUT ($(wc -l < "$OUT") lines)"
